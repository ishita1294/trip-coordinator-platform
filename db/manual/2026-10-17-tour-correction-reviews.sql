-- Apply once before the compatible ECS/Lambda application release. No backfill or source rewrite.
-- Older applications ignore this table/column; do not permit their generic booking writes during rollout.
BEGIN;
CREATE TABLE tour_correction_reviews (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 document_id bigint NOT NULL REFERENCES travel_documents(id),
 extraction_id bigint NOT NULL REFERENCES travel_document_extractions(id),
 actor_id bigint NOT NULL REFERENCES users(id),
 request_id uuid NOT NULL,
 extraction_sha256 varchar(64) NOT NULL CHECK (extraction_sha256 ~ '^[0-9a-f]{64}$'),
 document_sha256 varchar(64) NOT NULL CHECK (document_sha256 ~ '^[0-9a-f]{64}$'),
 changes_json text NOT NULL CHECK (jsonb_typeof(changes_json::jsonb)='array'),
 assessment_json text NOT NULL CHECK (jsonb_typeof(assessment_json::jsonb)='object'),
 created_at timestamptz NOT NULL,
 accepted_at timestamptz,
 accepted_by bigint REFERENCES users(id),
 version bigint NOT NULL DEFAULT 0 CHECK (version>=0),
 UNIQUE(document_id,actor_id,request_id),
 CHECK ((accepted_at IS NULL AND accepted_by IS NULL AND version=0) OR
        (accepted_at IS NOT NULL AND accepted_by IS NOT NULL AND accepted_by=actor_id AND version=1))
);
ALTER TABLE reservations ADD COLUMN correction_review_id bigint REFERENCES tour_correction_reviews(id);
CREATE FUNCTION protect_tour_correction_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Correction history is append-only'; END IF;
 IF (to_jsonb(NEW)-ARRAY['accepted_at','accepted_by','version']) IS DISTINCT FROM
    (to_jsonb(OLD)-ARRAY['accepted_at','accepted_by','version'])
    OR OLD.accepted_at IS NOT NULL OR NEW.accepted_at IS NULL OR NEW.accepted_by IS DISTINCT FROM OLD.actor_id
    OR NEW.version<>OLD.version+1 THEN
   RAISE EXCEPTION 'Immutable correction assessment or invalid acceptance transition';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tour_correction_history_immutable BEFORE UPDATE OR DELETE ON tour_correction_reviews
 FOR EACH ROW EXECUTE FUNCTION protect_tour_correction_history();
-- Protect provenance even when a future application write path accidentally bypasses the service.
CREATE FUNCTION protect_tour_correction_link() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' AND OLD.correction_review_id IS DISTINCT FROM NEW.correction_review_id THEN
   RAISE EXCEPTION 'Confirmed correction provenance is immutable';
 END IF;
 IF NEW.correction_review_id IS NOT NULL AND NOT EXISTS(
   SELECT 1 FROM tour_correction_reviews c JOIN travel_document_extractions e ON e.id=c.extraction_id
   JOIN travel_documents d ON d.id=e.travel_document_id
   WHERE c.id=NEW.correction_review_id AND c.extraction_id=NEW.confirmed_extraction_id
   AND c.document_id=d.id AND d.trip_id=NEW.trip_id AND c.accepted_at IS NOT NULL) THEN
   RAISE EXCEPTION 'Correction does not belong to the confirmed source';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER reservation_correction_link BEFORE INSERT OR UPDATE ON reservations
 FOR EACH ROW EXECUTE FUNCTION protect_tour_correction_link();
CREATE FUNCTION protect_original_tour_extraction() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'Original extraction records are immutable';
END $$;
CREATE TRIGGER original_extraction_immutable BEFORE UPDATE OR DELETE ON travel_document_extractions
 FOR EACH ROW EXECUTE FUNCTION protect_original_tour_extraction();
COMMIT;
