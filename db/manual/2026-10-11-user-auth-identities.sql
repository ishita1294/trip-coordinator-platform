BEGIN;
SET LOCAL lock_timeout = '3s';
SET LOCAL statement_timeout = '30s';
CREATE TABLE user_auth_identities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuer varchar(512) NOT NULL,
    subject varchar(255) NOT NULL,
    user_id bigint NOT NULL REFERENCES users(id),
    linked_at timestamptz NOT NULL,
    CONSTRAINT uq_user_auth_identity UNIQUE (issuer, subject),
    CONSTRAINT user_auth_identity_nonblank CHECK (btrim(issuer) <> '' AND btrim(subject) <> '')
);
CREATE INDEX user_auth_identities_user_idx ON user_auth_identities(user_id);
-- Identity ownership cannot be reassigned by later ORM or ordinary SQL updates.
CREATE FUNCTION protect_user_auth_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.issuer IS DISTINCT FROM OLD.issuer OR NEW.subject IS DISTINCT FROM OLD.subject
       OR NEW.user_id IS DISTINCT FROM OLD.user_id OR NEW.linked_at IS DISTINCT FROM OLD.linked_at THEN
        RAISE EXCEPTION 'Established authentication identity cannot be reassigned';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER user_auth_identity_immutable BEFORE UPDATE ON user_auth_identities
FOR EACH ROW EXECUTE FUNCTION protect_user_auth_identity();
COMMIT;
